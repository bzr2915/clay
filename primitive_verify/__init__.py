"""primitive_verify —— 通用单原语自动验证框架（框架草案 / 骨架）

================================================================================
一、这套框架解决什么
================================================================================
把"验证一个单原语"变成一次**纯数据提交**：

    提交 = ① bind.py（只写两行绑定：调哪个工程函数、参数怎么组装）
           ② spec.json（输入参数 + 预期结果，全部是数据）
           ③ 可选 input/*.gds（输入版图，如有）

然后运行一条命令，框架自己做：执行工程函数 → 读回真实输出 → 与预期逐项比对 →
判定 PASS / FAIL / INCONCLUSIVE → 生成报告与证据。

**判定由框架代码完成，AI 不参与判定。** AI 能做的只有三件事：
填参数、指认被测函数、调用运行命令。判定的比对规则、容差、通过条件全部
写在框架的 resolve.py / compare.py 里，AI 无权修改，也不需要修改。

================================================================================
二、为什么这样能排除"AI 过拟合"
================================================================================
本框架在结构上让"过拟合"无处可藏：

1. AI 的产物里没有判定代码。判定在 compare.py（固定文件，提交时校验哈希）。
2. bind.py 只能"取函数、传参数"，不得出现算术、条件、循环、字符串处理。
   由 bindcheck.py 静态检查（AST 级别），违规直接判失败，不运行。
3. 真实输出只来自工程函数：bind.py 调用后返回的对象被框架接管；版图从
   工程写出的 GDS 读回，不信任返回值中的任何"摘要"。
4. 预期是 spec.json 里的字面量，框架按规则机械比对，不做任何推断或"近似理解"。
5. 每个原语自动做"切断测试"：把被测工程函数体临时换成报错，测试必须失败。
   若 AI 在 bind.py 中偷偷算出了结果，切断后仍会产出 → 判 FAIL。
6. 若该原语属于某条完整流程，可指向 flow trace，框架自动做文件哈希比对与
   同输入输出比对（复用 primitive_probe.evidence.provenance）。
7. 报告内嵌 框架代码哈希 + 提交文件哈希 + 执行行记录，可复现可审计。

================================================================================
三、目录结构
================================================================================
    primitive_verify/
      __init__.py
      __main__.py        CLI：init / run / check / report
      registry.py        原语登记表：原语名 -> 被测工程函数、输出形态、比对配置
      resolve.py         把 spec 中的"路径表达式"解析为工程函数的返回值（唯一取值入口）
      compare.py         比对引擎：期望 vs 实际，产出逐项判定（唯一的判定处）
      bindcheck.py       bind.py 静态检查（禁止 AI 写逻辑）
      runner.py          执行：调用 bind → 取值 → 读回 GDS → 调用 compare
      severance.py       切断测试
      report.py          PASS/FAIL/INCONCLUSIVE 报告与证据打包
      primitives/
        <primitive_name>/
          bind.py         ← AI 填装（模板见下）
          spec.json       ← AI 填装（输入 + 预期）
          input/          ← 可选：输入版图
      expected_schema.py  spec.json 允许的字段与取值（JSON Schema 子集）

================================================================================
四、AI 填装提示（把下面这段原样贴给 AI 作为任务说明）
================================================================================
【任务】
你要为 CLAY 工程中的一个原语准备验证提交物。你只能创建/修改三样东西：
  primitive_verify/primitives/<name>/bind.py
  primitive_verify/primitives/<name>/spec.json
  primitive_verify/primitives/<name>/input/*.gds   （仅当原语需要版图输入）
其它任何文件都不许改。

【bind.py 必须遵守】
1. 只能 import clay.* 中的函数，和 primitive_probe.fixtures（仅当要构造输入形状）。
2. 主体只能有：函数定义、赋值、函数调用、属性访问、字面量。禁止：
   算术运算(+ - * / // % **)、比较、if/for/while/try、lambda、f-string、
   字符串方法、字典/列表推导式、round/max/min/sum/len 以外的内建调用（len 也禁止）。
   —— 如果发现自己"需要算点什么"，说明参数该写进 spec.json，而不是算在 bind.py 里。
3. 被测函数必须经 ctx.call(<函数>, ...) 调用，不得直接调用。
4. 返回 dict，键名与 spec.json 中 actual 各条目的 from 字段一致；每个值必须是
   工程函数返回对象上的既有属性/元素，不得再加工。版图请用 ctx.layout(<layout 对象>) 登记，
   由框架写出 GDS 并读回。
5. 不得包含任何与"预期"有关的内容；不得读取 spec.json。

【spec.json 必须遵守】
1. inputs：绑定时用到的全部参数，原样写清（框架会把它们原样传给 bind.run）。
2. actual：要取的实际输出清单，每条给出 from（取值路径）和类型。
   取值路径语法见 resolve.py 顶部注释（例如 "plan.count"、"polygons[0].bbox"、"checks['M1.1']"）。
3. expected：与 actual 一一对应的字面量预期，以及每条的比较方式：
     "eq"        完全相等
     "num"       允许绝对容差 tol（整数/小数）
     "bbox"      [x0,y0,x1,y1] 逐值相等，或给 tol
     "set"       元素集合相等（顺序无关）
     "count"     个数相等
     "reject"    期望工程函数抛出异常，exception 可写异常类型名
   预期必须由人/规则推导得出，不得先运行再抄结果。请在 derivation 中写明依据
   （引用 PDK 规则编号、公式或设计意图）。
4. 必须至少有一条 actual；不允许空提交；不允许出现 "skip" 或 "always_pass" 之类字段。

【运行】
  python -m primitive_verify check <name>     # 静态检查 bind.py 与 spec.json
  python -m primitive_verify run <name>       # 执行 + 比对 + 切断测试 + 报告
  python -m primitive_verify report <name>    # 只重新生成报告

【你会收到的结果】
  PASS          全部条目一致，切断测试成立，审计通过
  FAIL          有条目不一致 / bind.py 违规 / 切断测试不成立 / 审计不通过
  INCONCLUSIVE  工程函数拒绝执行、或条目无法解析（例如取值路径不存在）

================================================================================
五、新增一个原语需要人做的事
================================================================================
1. 在 registry.py 登记：原语名、被测工程函数的导入路径、输出形态（layout/data/coords）、
   是否属于某条 flow trace。
2. 让 AI 填 bind.py 与 spec.json（把第四节的提示给它）。
3. 人工复核 spec.json 的 expected 与 derivation，记录 spec 哈希（冻结预期）。
4. python -m primitive_verify run <name>，人工看报告中的"逐项对比表"。
5. 若预期写错，只能改 expected 并说明理由，不能改判定逻辑。
"""

